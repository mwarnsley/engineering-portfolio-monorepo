import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, renameSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { combineCoverage, normalizeReport, formatRunOutput } from './test-matrix.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const reports = mkdtempSync(join(tmpdir(), 'portfolio-test-matrix-'));
const targets = [
  { slug: 'meeting-application', path: 'apps/meeting-application', framework: 'Jest' },
  { slug: 'stock-trader', path: 'apps/stock-trader', framework: 'Vitest' },
  { slug: 'restaurant-finder', path: 'apps/restaurant-finder', framework: 'Jest' },
  { slug: 'chat-application', path: 'apps/chat-application/client', framework: 'Vitest' },
  { slug: 'chat-application', path: 'apps/chat-application/server', framework: 'Vitest' },
];
const groups = new Map();
const collectionFailures = [];
const env = { ...process.env, CI: 'true', FORCE_COLOR: '0', NO_COLOR: '1' };

for (const [index, target] of targets.entries()) {
  const directory = join(reports, String(index));
  const jsonFile = join(reports, `${index}.json`);
  const coverageArgs =
    target.framework === 'Jest'
      ? [
          '--coverage',
          '--coverageReporters=json-summary',
          `--coverageDirectory=${directory}`,
          '--json',
          `--outputFile=${jsonFile}`,
        ]
      : [
          '--coverage',
          '--coverage.reporter=json-summary',
          `--coverage.reportsDirectory=${directory}`,
          '--coverage.reportOnFailure',
          '--coverage.include=src/**/*.{ts,tsx,vue}',
          '--reporter=json',
          `--outputFile=${jsonFile}`,
        ];
  console.log(`Collecting tests and coverage: ${target.path}`);
  const run = spawnSync('pnpm', ['--filter', `./${target.path}`, 'test', ...coverageArgs], {
    cwd: root,
    env,
    encoding: 'utf8',
    maxBuffer: 20 * 1024 * 1024,
  });
  writeFileSync(join(reports, `${index}.log`), (run.stdout ?? '') + (run.stderr ?? ''));
  if (run.error) throw run.error;
  if (!existsSync(jsonFile) || !existsSync(join(directory, 'coverage-summary.json'))) {
    throw new Error(
      `Missing test/coverage report for ${target.path}. Existing snapshot preserved. Logs: ${reports}`
    );
  }
  const report = normalizeReport(JSON.parse(readFileSync(jsonFile, 'utf8')), root);
  const summary = JSON.parse(readFileSync(join(directory, 'coverage-summary.json'), 'utf8')).total;
  const group = groups.get(target.slug) ?? {
    framework: target.framework,
    testCount: 0,
    passedCount: 0,
    failedCount: 0,
    skippedCount: 0,
    suites: [],
    summaries: [],
    status: 'passed',
    coverageScope: [],
  };
  for (const key of ['testCount', 'passedCount', 'failedCount', 'skippedCount'])
    group[key] += report[key];
  group.suites.push(...report.suites);
  group.summaries.push(summary);
  group.coverageScope.push(
    target.framework === 'Jest'
      ? `${target.path}: collectCoverageFrom in Jest config (includes untested files)`
      : `${target.path}/src/**/*.{ts,tsx,vue} (includes untested files)`
  );
  if (run.status !== 0 || report.failedCount > 0) {
    group.status = 'failed';
    collectionFailures.push({ path: target.path, output: (run.stdout ?? '') + (run.stderr ?? '') });
  }
  groups.set(target.slug, group);
}

// Capture genuine Turbo output separately: runner-specific coverage flags cannot be shared.
const turboArgs = [
  'exec',
  'turbo',
  'run',
  'test',
  ...targets.map((target) => `--filter=./${target.path}`),
  '--force',
  '--output-logs=full',
  '--log-order=grouped',
];
console.log('Capturing uncached Turborepo verification output');
const turbo = spawnSync('pnpm', turboArgs, {
  cwd: root,
  env,
  encoding: 'utf8',
  maxBuffer: 20 * 1024 * 1024,
});
if (turbo.error) throw turbo.error;
const rawOutput = (turbo.stdout ?? '') + (turbo.stderr ?? '');
writeFileSync(join(reports, 'turbo.log'), rawOutput);
const recentRunDate = new Date().toISOString();
const testMatrix = Object.fromEntries(
  [...groups].map(([slug, { summaries, ...group }]) => [
    slug,
    {
      ...group,
      coverage: combineCoverage(summaries),
      recentRunDate,
    },
  ])
);
const testMatrixRun = {
  recentRunDate,
  command: `pnpm ${turboArgs.join(' ')}`,
  success: turbo.status === 0 && [...groups.values()].every((group) => group.status === 'passed'),
  output: formatRunOutput(collectionFailures, rawOutput, turbo.status, root),
};
if (!testMatrixRun.output) throw new Error('Turbo output was empty; existing snapshot preserved');
const outputFile = join(root, 'packages/project-registry/src/generated-test-matrix.ts');
const contents = `// Generated by pnpm --filter @engineering-portfolio/project-registry refresh:test-matrix.\n// Recorded evidence, not a live test service. Do not edit manually.\nimport type { ProjectTestSuite } from './index';\n\nexport const testMatrix: Record<string, ProjectTestSuite> = ${JSON.stringify(testMatrix, null, 2)};\n\nexport const testMatrixRun = ${JSON.stringify(testMatrixRun, null, 2)};\n`;
const temporary = join(reports, 'generated-test-matrix.ts');
writeFileSync(temporary, contents);
const format = spawnSync('pnpm', ['exec', 'prettier', '--stdin-filepath', outputFile], {
  cwd: root,
  input: contents,
  encoding: 'utf8',
  maxBuffer: 20 * 1024 * 1024,
});
if (format.status !== 0) throw new Error('Could not format snapshot; existing snapshot preserved');
// Keep replacement on the same filesystem and replace only after all reports validate.
writeFileSync(`${outputFile}.tmp`, format.stdout);
renameSync(`${outputFile}.tmp`, outputFile);
console.log(`Updated ${outputFile}\nRaw reports: ${reports}`);
if (!testMatrixRun.success) process.exitCode = 1;
